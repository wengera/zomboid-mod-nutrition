"""tools/food_hedonics.py (Plan 19 Task 5): the food hedonics table, generated per food type by the kernel's own rules
(K.hedonics.isPlain, K.hedonics.tasteClass, K.monotony.isStaple), in sync with the committed NR_Data_Hedonics.lua and
readable by its loader."""
import os
import sys

import pytest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

import food_hedonics as FH  # noqa: E402


@pytest.fixture(scope="module")
def made():
    rt = FH.runtime()
    return rt, FH.classify(rt)


def test_the_committed_file_is_in_sync(made):
    _, table = made
    with open(FH.OUT_LUA, encoding="utf-8", newline="") as fh:
        assert fh.read() == FH.render(table), "regenerate with python tools/food_hedonics.py --write"
    assert FH.main(["--check"]) == 0


def test_the_plain_foods_are_the_dense_single_macro_unpaired_ones(made):
    _, t = made
    for ft in ("Base.Lard", "Base.OilVegetable", "Base.OilOlive", "Base.Sugar", "Base.SugarBrown", "Base.Flour2",
               "Base.Rice", "Base.Pasta", "Base.Honey"):
        assert t[ft][0] is True, ft
    for ft in ("Base.Apple", "Base.Bread", "Base.Steak", "Base.TunaTinOpen", "Base.Chocolate", "Base.PeanutButter",
               "Base.Crisps", "Base.Candycane", "Base.OatsRaw"):
        assert t[ft][0] is False, ft
    # S2291's fat and sodium pairing takes the salted fats out (the ruling R1 reading, a concern of the Task 5 report)
    for ft in ("Base.Butter", "Base.Margarine", "Base.MayonnaiseFull", "Base.Bacon", "Base.Pretzel"):
        assert t[ft][0] is False, ft


def test_the_classes(made):
    _, t = made
    want = {"Base.Butter": "fatty", "Base.Lard": "fatty", "Base.PeanutButter": "fatty", "Base.Sugar": "sweet",
            "Base.Chocolate": "sweet", "Base.Apple": "sweet", "Base.CannedPeachesOpen": "sweet", "Base.Bread": "staple",
            "Base.Rice": "staple", "Base.Steak": "savoury", "Base.CannedBologneseOpen": "savoury"}
    for ft, cls in want.items():
        assert t[ft][1] == cls, ft
    assert {c for _, c in t.values()} == {"sweet", "savoury", "fatty", "staple"}


def test_the_sweet_reading_and_its_word_boundaries():
    assert FH.sweet({"food_type": "Candy"}, {}) is True
    assert FH.sweet({"tags": ["base:sugar"]}, {}) is True
    assert FH.sweet({}, {"fdc_description": "Pie, apple, commercially prepared"}) is True
    assert FH.sweet({}, {"fdc_description": "Pierogi, potato"}) is False               # whole words only
    assert FH.sweet({}, {"fdc_description": "Peppers, sweet, red, canned"}) is False   # "sweet" is no sweet word
    assert FH.sweet({}, {}) is False


def test_the_table_follows_a_dial(made):
    rt, t = made
    K = rt.globals().NutritionRevamp.kernel
    v0 = K.hedonics.PLAIN_KCAL
    try:
        K.hedonics.PLAIN_KCAL = 1000
        assert not any(p for p, _ in FH.classify(rt).values())
    finally:
        K.hedonics.PLAIN_KCAL = v0
    assert FH.classify(rt) == t


def test_the_loader(made):
    import lupa.lua51 as lua51
    rt = lua51.LuaRuntime(unpack_returned_tuples=True)
    rt.execute("NutritionRevamp = {}")
    with open(FH.OUT_LUA, encoding="utf-8") as fh:
        rt.execute(fh.read())
    get = rt.eval("NutritionRevamp.data.hedonics.get")
    assert get("Base.Lard") == (True, "fatty")
    assert get("Base.Bread") == (False, "staple")
    assert get("Base.NoSuchFood") == (False, None)
    with open(FH.OUT_LUA, encoding="utf-8") as fh:
        text = fh.read()
    assert "GENERATED by tools/food_hedonics.py" in text and "do not edit" in text


def test_the_tool_refuses_no_mode_and_two_modes():
    with pytest.raises(SystemExit):
        FH.main([])
    with pytest.raises(SystemExit):
        FH.main(["--check", "--write"])
