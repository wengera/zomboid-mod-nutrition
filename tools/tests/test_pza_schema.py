import pza_schema as PS  # noqa: E402


def run(argv, root):
    with redirect_stdout(io.StringIO()) as out:
        code = PS.main(argv, root=str(root))
    return code, out.getvalue()


def test_check_passes_on_a_fresh_write(tmp_path):
    assert run(["--write"], tmp_path)[0] == 0
    code, out = run(["--check"], tmp_path)
    assert code == 0 and "pza_schema: in sync" in out
    for rel in PS.OUTPUTS:
        assert os.path.isfile(os.path.join(str(tmp_path), rel))


@pytest.mark.parametrize("rel", sorted(PS.OUTPUTS))
def test_a_changed_byte_in_any_output_fails_check_naming_the_file(tmp_path, rel):
    run(["--write"], tmp_path)
    path = os.path.join(str(tmp_path), rel)
    with open(path, "rb") as fh:
        data = bytearray(fh.read())
    data[len(data) // 2] ^= 0x01
    with open(path, "wb") as fh:
        fh.write(bytes(data))
    code, out = run(["--check"], tmp_path)
    assert code == 1
    assert "pza_schema: %s differs" % rel in out
    assert out.strip().splitlines()[-1] == "pza_schema: out of sync; regenerate with --write"
    for other in PS.OUTPUTS:
        if other != rel:
            assert "%s differs" % other not in out


def test_a_missing_output_fails_check(tmp_path):
    run(["--write"], tmp_path)
    rel = sorted(PS.OUTPUTS)[0]
    os.remove(os.path.join(str(tmp_path), rel))
    code, out = run(["--check"], tmp_path)
    assert code == 1 and "pza_schema: %s differs" % rel in out


@pytest.mark.parametrize("argv", [["--check", "--write"], []])
def test_check_and_write_together_or_neither_are_refused(argv, tmp_path):
    with pytest.raises(SystemExit) as e:
        with redirect_stdout(io.StringIO()):
            PS.main(argv, root=str(tmp_path))
    assert e.value.code == 2


def test_a_crlf_copy_passes_check(tmp_path):
    run(["--write"], tmp_path)
    for rel in PS.OUTPUTS:
        path = os.path.join(str(tmp_path), rel)
        with open(path, "rb") as fh:
            data = fh.read()
        assert b"\r\n" not in data          # --write writes LF
        with open(path, "wb") as fh:
            fh.write(data.replace(b"\n", b"\r\n"))
    assert run(["--check"], tmp_path)[0] == 0


def test_the_repository_copies_are_in_sync():
    code, out = run(["--check"], PS.REPO)
    assert code == 0, out


def test_the_lua_header_obeys_the_kahlua_rules():
    text = PS.render_lua()
    assert "goto" not in text and "%d" not in text and "%g" not in text and "%G" not in text
    assert "\r" not in text
    assert kahlua_lint.lint_text(PS.LUA_REL, text) == []
    assert text.startswith("-- GENERATED by python tools/pza_schema.py from testing/agent/base/schema/pza1.json — never edit; "
                           "PZA.enc is the positional encoder (spec § 8).\n")


def test_the_lua_header_exports_every_group_and_record_encoder():
    text = PS.render_lua()
    sch = PS.load()
    for name in list(sch["groups"]) + list(sch["records"]) + ["frame", "map", "v"]:
        assert re.search(r"^PZA\.enc\.%s = " % name, text, re.M), name
    assert "pairs(" not in text and "table.sort" not in text


def load_py_module():
    spec = importlib.util.spec_from_loader("pza1_rendered", loader=None)
    mod = importlib.util.module_from_spec(spec)
    exec(compile(PS.render_py(), "pza1_rendered", "exec"), mod.__dict__)
    return mod


def test_tools_json_has_one_entry_per_action_type_with_the_required_fields():
    mod = load_py_module()
    tools = json.loads(PS.render_tools())
    assert [t["name"] for t in tools] == list(mod.ACTION_TYPES)
    classes = {c.TYPE: c for c in (getattr(mod, n) for n in dir(mod)) if isinstance(c, type) and getattr(c, "TYPE", "")}
    assert set(classes) == set(mod.ACTION_TYPES)
    for t in tools:
        assert set(t) == {"name", "description", "input_schema"}
        assert t["description"]
        sch = t["input_schema"]
        assert sch["type"] == "object"
        no_default = [f.name for f in dataclasses.fields(classes[t["name"]])
                      if f.default is dataclasses.MISSING and f.default_factory is dataclasses.MISSING]
        assert sch["required"] == no_default, t["name"]
        assert list(sch["properties"]) == [f.name for f in dataclasses.fields(classes[t["name"]])]
        for prop in sch["properties"].values():
            assert prop["description"] and "$ref" not in json.dumps(prop)


def test_the_tools_descriptions_are_the_schemas():
    raw = json.load(open(PS.SCHEMA, encoding="utf-8"))
    tools = {t["name"]: t for t in json.loads(PS.render_tools())}
    walk = tools["walkTo"]
    assert walk["description"] == raw["$defs"]["args_walkTo"]["description"]
    assert walk["input_schema"]["properties"]["gait"]["enum"] == ["walk", "run", "sprint"]
    assert walk["input_schema"]["properties"]["gait"]["default"] == "walk"
    assert tools["interact"]["input_schema"]["properties"]["filter"]["enum"] == raw["$defs"]["filter"]["enum"]


def test_every_schema_property_carries_a_one_line_description():
    raw = json.load(open(PS.SCHEMA, encoding="utf-8"))
    seen = []

    def walk(node, path):
        if isinstance(node, dict):
            for name, prop in (node.get("properties") or {}).items():
                assert isinstance(prop.get("description"), str) and prop["description"], path + "." + name
                assert "\n" not in prop["description"], path + "." + name
                seen.append(path + "." + name)
            for k, v in node.items():
                walk(v, path + "/" + k)
        elif isinstance(node, list):
            for v in node:
                walk(v, path)
    walk(raw, "")
    assert len(seen) > 100


def test_a_schema_inconsistency_is_refused(tmp_path):
    raw = json.load(open(PS.SCHEMA, encoding="utf-8"))
    raw["$defs"]["me"]["x-order"].append("ghost")
    bad = tmp_path / "bad.json"
    bad.write_text(json.dumps(raw), encoding="utf-8")
    with pytest.raises(ValueError):
        PS.load(str(bad))
    raw = json.load(open(PS.SCHEMA, encoding="utf-8"))
    raw["$defs"]["eventKind"]["enum"].append("ghost")
    bad.write_text(json.dumps(raw), encoding="utf-8")
    with pytest.raises(ValueError):
        PS.load(str(bad))


@pytest.mark.parametrize("prior", [0, 13, 14, "11", 11.0, True])
def test_an_x_prior_that_is_not_an_arity_below_the_groups_is_refused(tmp_path, prior):
    """X4 fix pass: a group's x-prior is an int in 1 .. len(x-order) - 1 (the arity before its last append)."""
