def test_every_schema_property_carries_a_one_line_description():
    raw = json.load(open(PS.SCHEMA, encoding="utf-8"))
    seen = []

    def walk(node, path):
        if isinstance(node, dict):
            for name, prop in (node.get("properties") or {}).items():
                assert isinstance(prop.get("description"), str) and prop["description"], path + "." + name
                assert "\n" not in prop["description"], path + "." + name
                seen.append(path + "." + name)
            for k, v in node.items():
                walk(v, path + "/" + k)
        elif isinstance(node, list):
            for v in node:
                walk(v, path)
    walk(raw, "")
    assert len(seen) > 100


