sys.path.insert(0, os.path.dirname(HERE))

import food_fills as FF  # noqa: E402


@pytest.fixture(scope="module")
def made():
    rt = FF.runtime()
    fills, base = FF.compute(rt)
    return rt, fills, base


def test_the_committed_file_is_in_sync(made):
    _, fills, base = made
    with open(FF.OUT_LUA, encoding="utf-8", newline="") as fh:
        assert fh.read() == FF.render(fills, base), "regenerate with python tools/food_fills.py --write"
    assert FF.main(["--check"]) == 0


def test_the_pre_meal_state_is_the_plate_worn_off_to_peckish(made):
    rt, _, base = made
    F = rt.globals().NR_FILL
    K = rt.globals().NutritionRevamp.kernel
    assert 120 < base < 300                                # the guide's plate wears off to Peckish in a few hours
    assert F.h0 == K.hungerCurve.inverse(0.15)             # the Peckish h_model, the curve's knot under HUNGER 0.15
    assert K.satiety.target(K.satiety.fullness(F.st), F.M, 1) > F.h0


def test_every_table_type_but_the_evolved_results_is_filled(made):
    _, fills, _ = made
    types = FF.table_types()
    evolved = FF.evolved_results()
    assert len(types) > 500 and set(fills) == set(types) - evolved
    assert "Base.Burger" in evolved and "Base.Burger" not in fills
    assert all(0 < h <= FF.CAP_H for h, _ in fills.values())


def test_the_hours_order_the_foods_as_a_meal_does(made):
    _, fills, _ = made
    h = {k: v[0] for k, v in fills.items()}
    assert h["Base.CannedBologneseOpen"] > h["Base.Apple"] > h["Base.Allsorts"]   # a meal, a fruit, a sweet
    assert h["Base.DriedKidneyBeans"] > h["Base.CannedBologneseOpen"]
    assert fills["Base.Apple"][1] == 94.59                 # the kcal is the table entry's calories


def test_more_of_one_food_fills_longer_and_volume_counts(made):
    rt, _, _ = made
    F = rt.globals().NR_FILL
    NR = rt.globals().NutritionRevamp
    rt.execute("""
        NR_FILL_GET = NutritionRevamp.data.nutrients.get
        NR_FILL_VOL = NutritionRevamp.data.volume.get
    """)
    try:
        rt.execute("""
            NutritionRevamp.data.nutrients.get = function(ft)
                local v = NR_FILL_GET("Base.Apple")
                if ft == "Two" then
                    for k, x in pairs(v) do v[k] = x * 2 end
                end
                return v
            end
            NutritionRevamp.data.volume.get = function(ft) if ft == "Bulky" then return 4 end return nil end
        """)
        one, _ = F.minutes("One", FF.CAP_MIN)
        two, _ = F.minutes("Two", FF.CAP_MIN)
        bulky, _ = F.minutes("Bulky", FF.CAP_MIN)
        assert two > one and bulky >= one                  # a bigger plate volume never fills less (Plan 15 Task 7)
    finally:
        rt.execute("""
            NutritionRevamp.data.nutrients.get = NR_FILL_GET
            NutritionRevamp.data.volume.get = NR_FILL_VOL
        """)
    assert NR.data.nutrients.get("Base.Apple").calories == 94.59


def test_the_loader_answers_hours_and_kcal_and_lists_its_types():
    import lupa.lua51 as lua51
    rt = lua51.LuaRuntime(unpack_returned_tuples=True)
    rt.execute("NutritionRevamp = {}")
    with open(FF.OUT_LUA, encoding="utf-8") as fh:
        rt.execute(fh.read())
    fills = rt.globals().NutritionRevamp.data.fills
    h, kcal = fills.get("Base.Apple")
    assert kcal == 94.59 and 0 < h < 3
    assert fills.get("Base.Nothing") is None
    types = fills.types()
    assert types[1] < types[2] and len(types) == len(FF.table_types()) - len(set(FF.table_types()) & FF.evolved_results())
    assert rt.eval("rawequal")(fills.types(), types)       # built once


