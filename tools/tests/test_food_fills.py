def test_the_generated_file_writes_no_exponent_and_names_its_generator():
    with open(FF.OUT_LUA, encoding="utf-8") as fh:
        text = fh.read()
    assert "GENERATED by tools/food_fills.py" in text
    assert not re.search(r"\d[eE][-+]?\d", text)
    assert FF.num(1e-7) == "0.000000" and FF.num(2.5) == "2.5"


